/**
 * 장소 사진을 화면 크기별로 얼마나 받을지.
 *
 * **왜 중요한가**: 저장된 사진 URL 은 대부분 1200px 짜리다. 그 한 장이 154KB 인데
 * 목록 카드는 72pt, 지도 핀은 42pt 로 그린다. 195곳이면 **30MB를 받아서
 * 엄지손톱만 하게** 그리는 셈이라 처음 화면이 눈에 띄게 느렸다.
 *
 * 같은 사진이 w=300 이면 16KB, w=200 이면 8KB다 (실측).
 *
 * 웹·앱이 같은 값을 써야 사진 캐시(place_photos)도 같은 것을 재사용한다.
 * 서로 다른 너비를 요청하면 같은 사진을 너비 수만큼 따로 받게 된다.
 */
export const PHOTO_W = {
  /** 지도 핀 (42pt 원형) */
  pin: 200,
  /** 목록 카드 썸네일 (60~80pt) */
  thumb: 300,
  /** 카드 전체 폭 이미지 (여행 상세 등) */
  card: 800,
  /** 상세 화면 큰 사진 */
  full: 1200,
} as const

export type PhotoSize = keyof typeof PHOTO_W
