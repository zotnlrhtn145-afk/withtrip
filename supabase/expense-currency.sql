-- WITHTRIP: 해외 결제 정산 (외화) — 순수 "추가"만 하는 마이그레이션
--
-- 대원칙 준수 확인:
--   - 기존 행을 하나도 바꾸지 않습니다 (전부 기본값이 있는 칸 추가)
--   - 지금 쌓인 지출은 전부 원화라 기본값 그대로가 정답입니다
--   - 실패해도 지금 정산은 그대로 동작합니다
--
-- ─────────────────────────────────────────────────────────────
-- 왜 필요한가
-- ─────────────────────────────────────────────────────────────
-- 지금 `expenses.amount` 는 숫자 하나뿐이라 **10,000엔과 10,000원이 구별되지
-- 않는다.** 도쿄·오사카·호치민 여행이 이미 있어서 지출을 넣는 순간 터진다.
--
-- ─────────────────────────────────────────────────────────────
-- 왜 이렇게 나누나 (환율 vs 수수료)
-- ─────────────────────────────────────────────────────────────
--     실제 청구액 = 현지금액 × 기준환율(그 날짜) × (1 + 수수료율)
--                              ↑ 매일 바뀐다      ↑ 카드가 정해지면 고정
--
-- ⚠️ **바뀌는 것과 고정된 것을 반드시 나눠 담아야 한다.** 실효환율 하나로 뭉쳐
--    두면 여행 내내 같은 값을 쓰게 되는데, 5일 사이 기준환율이 1.4% 움직인
--    실측 예에서 1500만원 여행 기준 **1인당 3만원**이 어긋났다.
--
--   · `expenses.fx_rate`   — 그 지출을 기록한 날의 기준환율. 지출마다 다르다
--   · `trips.fx_fee_rate`  — 카드 수수료율. 여행 하나에 하나
--
-- ⚠️ 환산 결과(원화)를 저장하지 않는다. 수수료율을 나중에 고치면 **모든 지출이
--    한꺼번에 다시 계산돼야** 하는데, 저장해 두면 그때 전부 갱신해야 하고
--    한 건이라도 빠지면 정산이 조용히 틀어진다. 읽을 때 계산한다.


-- ─────────────────────────────────────────────────────────────
-- 1) 지출에 통화와 그날 환율
-- ─────────────────────────────────────────────────────────────
alter table public.expenses
  add column if not exists currency text not null default 'KRW',
  add column if not exists fx_rate numeric not null default 1;

comment on column public.expenses.currency is
  '통화 코드(KRW·JPY·USD…). amount 는 이 단위다. 기본 KRW.';

comment on column public.expenses.fx_rate is
  '기록 시점의 기준환율(이 통화 1단위 = 몇 원). 원화면 1. '
  '⚠️ 수수료는 포함하지 않는다 — 수수료는 trips.fx_fee_rate 에 따로 있다. '
  '⚠️ 지출마다 다르다(날마다 환율이 바뀐다). 나중에 다시 조회하지 않고 이 값을 쓴다.';

-- 원화가 아닌 지출만 빠르게 찾는다 (환율 맞추기 화면에서 쓴다)
create index if not exists expenses_foreign_idx
  on public.expenses (trip_id) where currency <> 'KRW';


-- ─────────────────────────────────────────────────────────────
-- 2) 여행에 카드 수수료율
-- ─────────────────────────────────────────────────────────────
-- 기본값 2.3% 의 근거:
--   국제브랜드 수수료 약 1.0~1.1% + 해외서비스 수수료 약 0.2~0.35%
--   + 전신환매도율이 기준환율보다 약 1% 높음  →  합계 2.2~2.5%
--
-- ⚠️ **0 으로 두면 안 된다.** 수수료는 방향이 늘 한쪽(더 나온다)이라, 빼놓으면
--    정산이 항상 모자라게 나온다. 1500만원 여행에서 1인당 11만원이다.
alter table public.trips
  add column if not exists fx_fee_rate numeric not null default 0.023,
  add column if not exists fx_calibrated_at timestamptz;

comment on column public.trips.fx_fee_rate is
  '카드 해외 결제 수수료율(0.023 = 2.3%). 기본값은 어림값이고, 결제 한 건의 '
  '실제 청구액으로 역산해 정확히 맞출 수 있다.';

comment on column public.trips.fx_calibrated_at is
  '수수료율을 실제 청구액으로 맞춘 시각. NULL 이면 아직 어림값이라는 뜻 — '
  '화면에서 「약」 을 붙여야 한다.';
