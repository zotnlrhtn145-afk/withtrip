-- 사람마다 다른 금액으로 나눠 내기.
--
-- 신고/요청: "총 250만원이 나와도 본인은 50만원만 내고 남은 금액은 남은 사람끼리
--             나눠 내거나, 일정 금액을 2명이 나눠 내고 남은 걸 나머지가 나눠 내는 경우"
--
-- ## ⚠️ 「모드」를 만들지 않는다
--
-- 균등/직접/비율 같은 **모드를 두면** 사용자가 먼저 모드를 고르고 시작해야 하고,
-- 한 지출 안에서 섞어 쓸 수가 없다. 그런데 실제로 필요한 건 늘 섞인 형태다 —
-- "한 명만 50만 고정, 나머지는 알아서 나눠".
--
-- 그래서 **칸 하나**만 둔다.
--
--     비어 있음(null)  →  남은 금액을 나눠 갖는 사람
--     숫자             →  이 사람은 딱 이만큼
--
-- 계산은 한 줄이다. **총액 − 정한 사람들 합계 = 남은 금액**, 그걸 비어 있는
-- 사람들끼리 나눈다. 요청하신 두 경우가 모두 이 한 줄로 풀린다.
--
-- ⚠️ **기존 데이터는 전부 `null` 이다.** 지금까지의 정산은 그대로 균등으로
--    남는다 — 깨지는 것이 없다. 이게 칸을 추가하는 방식을 고른 이유다.
--
-- ⚠️ 원 단위 정수다. 나눠떨어지지 않는 몫(200만 ÷ 3)은 **화면 쪽에서** 맨 앞
--    사람에게 1원씩 더 붙인다. 그래야 각자 낼 금액의 합이 총액과 정확히 맞는다.

alter table public.expense_participants
  add column if not exists share_amount integer;

comment on column public.expense_participants.share_amount is
  '이 사람이 낼 금액(원). 비어 있으면 남은 금액을 다른 빈칸인 사람들과 나눠 낸다.';
