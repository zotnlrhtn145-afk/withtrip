const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const filename = path.join(__dirname, '../lib/template-query.ts')
const exported = {}
vm.runInNewContext(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exported, URLSearchParams })
const parse = input => JSON.parse(JSON.stringify(exported.parseTemplateQuery(new URLSearchParams(input))))
const id = '11111111-2222-3333-4444-555555555555'
assert.deepEqual(parse(''), {kind:'hub'})
assert.deepEqual(parse('unrelated=1'), {kind:'hub'})
assert.deepEqual(parse(`ownerId=${id}`), {kind:'profile',ownerId:id,page:0})
assert.deepEqual(parse(`ownerId=${id}&page=1`), {kind:'profile',ownerId:id,page:1})
assert.deepEqual(parse('slug=부산-2박3일-b4af7388'), {kind:'detail',slug:'부산-2박3일-b4af7388'})
for (const input of ['ownerId=', 'ownerId=invalid', 'page=0', `ownerId=${id}&page=-1`, `ownerId=${id}&page=1.5`, `ownerId=${id}&page=0001`, `ownerId=${id}&page=100000`, 'slug=../secret-b4af7388', 'slug=invalid', `slug=부산-b4af7388&ownerId=${id}`, 'slug=부산-b4af7388&page=0']) assert.deepEqual(parse(input),{kind:'invalid'},input)
const api=fs.readFileSync(path.join(__dirname,'../lib/templates-api.ts'),'utf8')
assert.match(api, /\.eq\("is_public", true\)/)
assert.match(api, /fetchTemplateCards\(size, \{ ownerId, offset: page \* size \}\)/)
console.log('profile template query: 18 checks passed (hub, pagination, slug and invalid input)')
